def init_opensim():
    import opensim as osim
    osim.Logger.setLevelString("Error")
    if hasattr(osim, "ModelVisualizer"):
        osim.ModelVisualizer.addDirToGeometrySearchPaths(os.path.join(REPO_ROOT, "osim_files", "Geometry"))
    osim.LoadOpenSimLibraryExact(AFF_DLL)
    osim.LoadOpenSimLibraryExact(CTRL_DLL)
    osim.LoadOpenSimLibraryExact(FIX_DLL)
    return osim


def load_sto(path):
    with open(path, "r", errors="replace") as fh:
        lines = fh.readlines()
    idx = next(i for i, l in enumerate(lines) if "endheader" in l.lower())
    hdr = lines[idx + 1].split()
    data = np.loadtxt(lines[idx + 2:])
    if data.ndim == 1:
        data = data[None, :]
    return hdr, data


def kuo_to_hyoid_muscle_name(kuo_nm):
    if kuo_nm == "cleid_mas_r":
        return "cleid_mast"
    if kuo_nm == "cleid_mast_l":
        return "cleid_mast_L"
    if kuo_nm.endswith("_r"):
        return kuo_nm[:-2]
    if kuo_nm.endswith("_l"):
        return kuo_nm[:-2] + "_L"
    return kuo_nm


def make_variant_osim(tag, sk_pitch, sk_ry, sc_scale, disable_lim=False, disable_lig=False):
    """Create a temporary variant .osim in scratch with scaled BushingForce k/c and optional limit/lig toggles."""
    dst = os.path.join(SCRATCH_DIR, f"cal_{tag}.osim")
    tree = ET.parse(HYOID_KUO)
    root = tree.getroot()
    for bf in root.findall(".//ForceSet/objects/BushingForce"):
        rk = [float(x) for x in bf.findtext("rotational_stiffness").split()]
        rc = [float(x) for x in bf.findtext("rotational_damping").split()]
        # OpenSim BushingForce order: [rx (roll), ry (yaw), rz (pitch)]
        rk_new = [rk[0] * sk_ry, rk[1] * sk_ry, rk[2] * sk_pitch]
        rc_new = [rc[0] * sc_scale, rc[1] * sc_scale, rc[2] * sc_scale]
        bf.find("rotational_stiffness").text = f"{rk_new[0]:.6f} {rk_new[1]:.6f} {rk_new[2]:.6f}"
        bf.find("rotational_damping").text = f"{rc_new[0]:.6f} {rc_new[1]:.6f} {rc_new[2]:.6f}"
    if disable_lim:
        for lf in root.findall(".//ForceSet/objects/CoordinateLimitForce"):
            ap = lf.find("appliesForce")
            if ap is None:
                ap = ET.SubElement(lf, "appliesForce")
            ap.text = "false"
    if disable_lig:
        for dl in root.findall(".//ForceSet/objects/DynamicLigamentForce"):
            ap = dl.find("appliesForce")
            if ap is None:
                ap = ET.SubElement(dl, "appliesForce")
            ap.text = "false"
    tree.write(dst, encoding="utf-8", xml_declaration=True)
    return dst


def attach_external_force(osim, model, mot_path):
    _, data = load_sto(mot_path)
    pf = osim.PrescribedForce("Ext_Force", model.getBodySet().get("skull"))
    pf.setForceIsInGlobalFrame(True)
    pf.setPointIsInGlobalFrame(False)
    for setter, cols in ((pf.setForceFunctions, (1, 2, 3)), (pf.setPointFunctions, (4, 5, 6))):
        fns = []
        for ci in cols:
            fn = osim.PiecewiseLinearFunction()
            for row in data:
                fn.addPoint(float(row[0]), float(row[ci]))
            fns.append(fn)
        setter(*fns)
    model.addForce(pf)


def _impact_worker(task):
    osim = init_opensim()
    osim_path = task["osim_path"]
    cname = task["cname"]
    mot_path = task["mot_path"]
    ctrl_sto = task["ctrl_sto"]
    axis = task["axis"]
    tone_mode = task["tone_mode"]  # "kuo_matched" | "passive_001" | "osteo_nomus"

    m = osim.Model(osim_path)
    cset = m.updControllerSet()
    for i in range(cset.getSize()):
        cset.get(i).setEnabled(False)

    mus_set = m.getMuscles()
    hyo_act = {}
    if tone_mode == "kuo_matched":
        chdr, cd = load_sto(ctrl_sto)
        for i in range(1, len(chdr)):
            hyo_act[kuo_to_hyoid_muscle_name(chdr[i])] = float(cd[0, i])
    elif tone_mode == "passive_001":
        for i in range(mus_set.getSize()):
            hyo_act[mus_set.get(i).getName()] = 0.001

    if tone_mode == "osteo_nomus":
        for i in range(mus_set.getSize()):
            mus_set.get(i).set_appliesForce(False)
    else:
        pctrl = osim.PrescribedController()
        pctrl.setName("OpenLoopTone")
        for i in range(mus_set.getSize()):
            mu = mus_set.get(i)
            pctrl.addActuator(mu)
            pctrl.prescribeControlForActuator(mu.getName(), osim.Constant(hyo_act.get(mu.getName(), 0.001)))
        m.addController(pctrl)

    attach_external_force(osim, m, mot_path)
    state = m.initSystem()
    if tone_mode != "osteo_nomus":
        for i in range(mus_set.getSize()):
            mu = osim.Millard2012EquilibriumMuscle.safeDownCast(mus_set.get(i))
            if mu is not None:
                mu.setActivation(state, hyo_act.get(mu.getName(), 0.001))
        m.equilibrateMuscles(state)

    mgr = osim.Manager(m)
    mgr.setIntegratorAccuracy(1e-4)
    mgr.initialize(state)

    cs = m.getCoordinateSet()
    c1 = cs.get(f"{axis}1")
    c2 = cs.get(f"{axis}2")
    fset = m.getForceSet()
    dl_list = [fset.get(i) for i in range(fset.getSize()) if fset.get(i).getConcreteClassName() == "DynamicLigamentForce"]

    q_sim = np.zeros(len(T_GRID))
    u_sim = np.zeros(len(T_GRID))
    max_lig_N = 0.0
    max_lig_nm = ""
    err_str = None
    t_wall0 = time.time()
    for k, t_tgt in enumerate(T_GRID):
        if k > 0:
            if time.time() - t_wall0 > 45.0:
                err_str = f"timeout@t={t_tgt:.3f}s"
                q_sim[k:] = q_sim[k - 1]
                break
            try:
                state = mgr.integrate(float(t_tgt))
            except Exception as e:
                err_str = f"t={t_tgt:.3f}s: {e}"
                q_sim[k:] = q_sim[k - 1]
                break
        m.realizeVelocity(state)
        q_sim[k] = math.degrees(float(c1.getValue(state) + c2.getValue(state)))
        u_sim[k] = math.degrees(float(c1.getSpeedValue(state) + c2.getSpeedValue(state)))
        for lg in dl_list:
            ft = float(lg.getOutput("tension").getValueAsString(state))
            if ft > max_lig_N:
                max_lig_N = ft
                max_lig_nm = lg.getName()

    ipk = int(np.argmax(np.abs(q_sim)))
    return {
        "tag": task["tag"],
        "cname": cname,
        "tone_mode": tone_mode,
        "peak_deg": round(float(q_sim[ipk]), 2),
        "t_peak_ms": round(float(T_GRID[ipk] * 1000.0), 1),
        "peak_dps": round(float(np.max(np.abs(u_sim))), 1),
        "max_lig_N": round(max_lig_N, 1),
        "max_lig_name": max_lig_nm,
        "q_sim_deg": q_sim.tolist(),
        "err": err_str,
    }


def _corridor_0g_worker(task):
    """Instant (~0.5s) exact 0g osteoligamentous (muscles OFF) moment-angle curve for HYOID variant
    by evaluating total passive restoring moment (Bushings + CoordinateLimitForces + 67 Ligaments)
    along physiological upper/lower split ratios and inverting for M = 1.5, 2.5, 3.5 Nm."""
    osim = init_opensim()
    m = osim.Model(task["osim_path"])
    m.setGravity(osim.Vec3(0.0, 0.0, 0.0))
    for i in range(m.updControllerSet().getSize()):
        m.updControllerSet().get(i).setEnabled(False)
    for i in range(m.getMuscles().getSize()):
        m.getMuscles().get(i).set_appliesForce(False)
    st = m.initSystem()
    mas = osim.MomentArmSolver(m)
    bset = m.getBodySet()
    fset = m.getForceSet()
    cset = m.updCoordinateSet()

    bushing_names = [
        ("Spine_C7_Bushing", "spine", "cerv7"), ("C7_C6_Bushing", "cerv7", "cerv6"),
        ("C6_C5_Bushing", "cerv6", "cerv5"),    ("C5_C4_Bushing", "cerv5", "cerv4"),
        ("C4_C3_Bushing", "cerv4", "cerv3"),    ("C3_C2_Bushing", "cerv3", "cerv2"),
        ("C2_C1_Bushing", "cerv2", "cerv1"),    ("C1_skull_Bushing", "cerv1", "skull"),
    ]
    bushings = [fset.get(nm) for nm, _, _ in bushing_names]
    lim_forces = {cn: osim.CoordinateLimitForce.safeDownCast(fset.get(f"{cn}_physical_limit"))
                  for cn in ("pitch1", "pitch2", "roll1", "roll2", "yaw1", "yaw2")}
    dl_list = [fset.get(i) for i in range(fset.getSize()) if fset.get(i).getConcreteClassName() == "DynamicLigamentForce"]
    dl_paths = [osim.GeometryPath.safeDownCast(lg.getPropertyByName("GeometryPath").getValueAsObject()) for lg in dl_list]

    all_neck = ("pitch1", "pitch2", "roll1", "roll2", "yaw1", "yaw2")

    def reset_state_q(q_map):
        for cn in all_neck:
            cset.get(cn).setValue(st, float(q_map.get(cn, 0.0)), False)
            cset.get(cn).setSpeedValue(st, 0.0)
        m.assemble(st)
        m.realizeVelocity(st)

    def meas_rel_angles(q_map):
        reset_state_q(q_map)
        angs = []
        for _, pb, cb in bushing_names:
            Rp = bset.get(pb).getTransformInGround(st).R()
            Rc = bset.get(cb).getTransformInGround(st).R()
            Rp_np = np.array([[Rp.get(r, c) for c in range(3)] for r in range(3)], dtype=float)
            Rc_np = np.array([[Rc.get(r, c) for c in range(3)] for r in range(3)], dtype=float)
            Rrel = Rp_np.T @ Rc_np
            rx = math.atan2(-Rrel[1, 2], Rrel[2, 2])
            ry = math.asin(max(-1.0, min(1.0, Rrel[0, 2])))
            rz = math.atan2(-Rrel[0, 1], Rrel[0, 0])
            angs.append((rx, ry, rz))
        return angs

    eps_q = 0.01
    coup_fracs = {}
    for axis_name, idx_xyz, cnames in (("pitch", 2, ("pitch1", "pitch2")), ("roll", 0, ("roll1", "roll2")), ("yaw", 1, ("yaw1", "yaw2"))):
        coup_fracs[axis_name] = {}
        for cn in cnames:
            ap = meas_rel_angles({cn: +eps_q})
            am = meas_rel_angles({cn: -eps_q})
            coup_fracs[axis_name][cn] = [(ap[j][idx_xyz] - am[j][idx_xyz]) / (2.0 * eps_q) for j in range(8)]

    def eval_moment(axis_name, tot_deg, split1):
        idx_xyz = {"roll": 0, "yaw": 1, "pitch": 2}[axis_name]
        c1 = cset.get(f"{axis_name}1")
        c2 = cset.get(f"{axis_name}2")
        reset_state_q({
            f"{axis_name}1": math.radians(split1 * tot_deg),
            f"{axis_name}2": math.radians((1.0 - split1) * tot_deg),
        })
        tau_bush = 0.0
        for j, bf in enumerate(bushings):
            rv = bf.getRecordValues(st)
            t_b2 = float(rv.get(9 + idx_xyz))
            tau_bush += 0.5 * (coup_fracs[axis_name][f"{axis_name}1"][j] + coup_fracs[axis_name][f"{axis_name}2"][j]) * t_b2
        tau_lim = 0.5 * (float(lim_forces[f"{axis_name}1"].calcLimitForce(st)) + float(lim_forces[f"{axis_name}2"].calcLimitForce(st)))
        tau_lig = 0.0
        for k, lg in enumerate(dl_list):
            ft = float(lg.getOutput("tension").getValueAsString(st))
            if ft <= 1e-12:
                continue
            r_avg = 0.5 * (mas.solve(st, c1, dl_paths[k]) + mas.solve(st, c2, dl_paths[k]))
            tau_lig += r_avg * ft
        return -(tau_bush + tau_lim + tau_lig)

    out = {}
    for dname, ax, sgn, split1, grid in [
        ("Ext",   "pitch", +1.0, 0.35, np.linspace(0, 62, 17)),
        ("Flex",  "pitch", -1.0, 0.35, np.linspace(0, -56, 17)),
        ("LatR",  "roll",  +1.0, 0.25, np.linspace(0, 48, 17)),
        ("AxRot", "yaw",   +1.0, 0.55, np.linspace(0, 72, 17)),
    ]:
        ms = [sgn * eval_moment(ax, float(g), split1) for g in grid]
        pts = []
        for mag in (1.5, 2.5, 3.5):
            deg_val = float(np.interp(mag, ms, grid))
            pts.append({"M_Nm": mag, "deg": round(deg_val, 2)})
        out[dname] = pts
    return {"tag": task["tag"], "corridors": out}


def main():
    t0 = time.time()
    with open(EXP_JSON) as f:
        exp_data = json.load(f)
    kuo_cor = exp_data["corridors"]

    # -------------------------------------------------------------------------
    # Part A: Mechanical Decomposition Ladder (Controller OFF)
    # -------------------------------------------------------------------------
    partA_specs = [
        ("A0_Base100",       1.00, 1.00, 1.00, False, False, "kuo_matched"),
        ("A1_LowDamp1pct",   1.00, 1.00, 0.01, False, False, "kuo_matched"),
        ("A2_LowBush1pct",   0.01, 0.01, 0.01, False, False, "kuo_matched"),
        ("A3_LowBushNoLim",  0.01, 0.01, 0.01, True,  False, "kuo_matched"),
        ("A4_Passive001",    1.00, 1.00, 1.00, False, False, "passive_001"),
        ("A5_OsteoNoMus",    1.00, 1.00, 1.00, False, False, "osteo_nomus"),
        ("A6_OsteoLowBush",  0.01, 0.01, 0.01, False, False, "osteo_nomus"),
    ]

    # -------------------------------------------------------------------------
    # Part B: Bushing Disc-Only Calibration Grid (Controller OFF, kuo_matched)
    # (tag, sk_pitch, sk_roll_yaw, sc_scale)
    # -------------------------------------------------------------------------
    partB_specs = [
        ("B_k100_c100", 1.00, 1.00, 1.00),
        ("B_k50_c30",   0.50, 0.50, 0.30),
        ("B_k35_c20",   0.35, 0.50, 0.20),
        ("B_k25_c15",   0.25, 0.50, 0.15),
        ("B_k15_c10",   0.15, 0.35, 0.10),
        ("B_k10_c05",   0.10, 0.35, 0.05),
    ]

    variant_paths = {}
    tasks_imp = []
    tasks_0g = []

    for tag, skp, skry, sc, dlim, dlig, tmode in partA_specs:
        vp = make_variant_osim(tag, skp, skry, sc, disable_lim=dlim, disable_lig=dlig)
        variant_paths[tag] = vp
        for cname, mot_f, ctrl_f, axis in IMPACTS:
            if cname in ("Flex_Relax", "Flex_Football", "Lat_Relax", "Lat_Football"):
                tasks_imp.append({
                    "tag": tag, "osim_path": vp, "cname": cname,
                    "mot_path": os.path.join(SCRATCH_DIR, mot_f),
                    "ctrl_sto": os.path.join(SUBJ_A_DIR, "Controllers", ctrl_f),
                    "axis": axis, "tone_mode": tmode,
                })

    for tag, skp, skry, sc in partB_specs:
        vp = make_variant_osim(tag, skp, skry, sc, disable_lim=False, disable_lig=False)
        variant_paths[tag] = vp
        for cname, mot_f, ctrl_f, axis in IMPACTS:
            tasks_imp.append({
                "tag": tag, "osim_path": vp, "cname": cname,
                "mot_path": os.path.join(SCRATCH_DIR, mot_f),
                "ctrl_sto": os.path.join(SUBJ_A_DIR, "Controllers", ctrl_f),
                "axis": axis, "tone_mode": "kuo_matched",
            })
        tasks_0g.append({"tag": tag, "osim_path": vp})

    n_workers = min(8, max(4, (os.cpu_count() or 4) - 2))
    print(f"Dispatching {len(tasks_imp)} impact sims + {len(tasks_0g)} 0g corridor sweeps across {n_workers} workers...")
    imp_res = {}
    cor_res = {}
    with ProcessPoolExecutor(max_workers=n_workers) as ex:
        futs = {}
        for t in tasks_imp:
            futs[ex.submit(_impact_worker, t)] = ("imp", (t["tag"], t["cname"]))
        for t in tasks_0g:
            futs[ex.submit(_corridor_0g_worker, t)] = ("cor", t["tag"])
        for fut in as_completed(futs):
            kind, key = futs[fut]
            res = fut.result()
            if kind == "imp":
                imp_res[key] = res
            else:
                cor_res[key] = res["corridors"]

    print("\n=== PART A: PASSIVE MECHANICAL DECOMPOSITION (Controller OFF) ===")
    print(f"  {'Variant':18s} | {'Flex_Relax':>11s} | {'Flex_Footb':>11s} | {'Lat_Relax':>11s} | {'Lat_Footb':>11s}")
    print(f"  {'Kuo A-J Mean±SD':18s} | {'+57.3±10.1°':>11s} | {'+76.0±24.4°':>11s} | {'-32.8±12.0°':>11s} | {'-46.5±22.8°':>11s}")
    for tag, *_ in partA_specs:
        fr = imp_res[(tag, "Flex_Relax")]["peak_deg"]
        ff = imp_res[(tag, "Flex_Football")]["peak_deg"]
        lr = imp_res[(tag, "Lat_Relax")]["peak_deg"]
        lf = imp_res[(tag, "Lat_Football")]["peak_deg"]
        print(f"  {tag:18s} | {fr:+10.2f}° | {ff:+10.2f}° | {lr:+10.2f}° | {lf:+10.2f}°")

    print("\n=== PART B: BUSHING STIFFNESS & DAMPING CALIBRATION SWEEP (Controller OFF) ===")
    print(f"  {'Variant':13s} | {'FlexRel':>8s} {'FlexFB':>8s} {'LatRel':>8s} {'LatStf':>8s} {'LatFB':>8s} | "
          f"{'0gExt2.5':>8s} {'0gFlx2.5':>8s} {'0gLat2.5':>8s} {'0gYaw2.5':>8s} | {'Z-score':>7s}")
    scored = []
    for tag, skp, skry, sc in partB_specs:
        fr = imp_res[(tag, "Flex_Relax")]["peak_deg"]
        ff = imp_res[(tag, "Flex_Football")]["peak_deg"]
        lr = imp_res[(tag, "Lat_Relax")]["peak_deg"]
        ls = imp_res[(tag, "Lat_Stiff")]["peak_deg"]
        lf = imp_res[(tag, "Lat_Football")]["peak_deg"]
        c0 = cor_res[tag]
        e25 = c0["Ext"][1]["deg"]
        f25 = c0["Flex"][1]["deg"]
        l25 = c0["LatR"][1]["deg"]
        y25 = c0["AxRot"][1]["deg"]
        # RMS z-score across the 5 Kuo A-J impact targets + 4 cadaveric midpoints
        zs = [
            (fr - kuo_cor["Flex_Relax"]["peak_deg_mean"]) / kuo_cor["Flex_Relax"]["peak_deg_sd"],
            (ff - kuo_cor["Flex_Football"]["peak_deg_mean"]) / kuo_cor["Flex_Football"]["peak_deg_sd"],
            (lr - kuo_cor["Lat_Relax"]["peak_deg_mean"]) / kuo_cor["Lat_Relax"]["peak_deg_sd"],
            (ls - kuo_cor["Lat_Stiff"]["peak_deg_mean"]) / kuo_cor["Lat_Stiff"]["peak_deg_sd"],
            (lf - kuo_cor["Lat_Football"]["peak_deg_mean"]) / kuo_cor["Lat_Football"]["peak_deg_sd"],
            (e25 - 47.0) / 9.0,    # +38..+56 deg
            (f25 - (-41.5)) / 6.5, # -48..-35 deg
            (l25 - 36.0) / 6.0,    # 30..42 deg
            (y25 - 63.5) / 8.5,    # 55..72 deg
        ]
        z_rms = float(np.sqrt(np.mean(np.square(zs))))
        scored.append((z_rms, tag, skp, skry, sc))
